bank = TEST
positions = collections.Counter()

def add(kind, state, instruction, criteria, label, tag):
    counts = collections.Counter(x['type'] for x in bank)
    prefix = 'manual_v2' if bank is TEST else 'cal_v2'
    bank.append(dict(id=f'{prefix}_{kind}_{counts[kind]+1:03}', type=kind,
        state=state, instructions=instruction, criteria=criteria, label=str(label).lower(), tag=tag))

def c(state, instruction, criteria, gold, tag='meaning'):
    ds=criteria.split('|'); k=len(ds)
    p=min(range(k), key=lambda p:(positions[(id(bank),k,p)],p))
    positions[(id(bank),k,p)]+=1
    selected=ds.pop(gold);ds.insert(p,selected)
    add('choice',state,instruction,{f'option_{j}':v for j,v in enumerate(ds)},f'option_{p}',tag)

def n(state,instruction,gold,tag):
    add('noul',state,instruction,{'false':'いいえ','true':'はい'},gold,tag)

def s(state,instruction,criteria,gold,tag):
    add('score',state,instruction,criteria.split('|'),gold,tag)

