position_counts = Counter()

def add(kind, state, instructions, criteria, gold, tag):
    prefix = 'accept' if bank is TEST else 'cal'
    counts = Counter(x['type'] for x in bank)
    bank.append(dict(id=f'{prefix}_{kind}_{counts[kind]+1:03}', type=kind,
                     state=state, instructions=instructions, criteria=criteria,
                     label=str(gold).lower(), tag=tag))

def c(state, instructions, descriptions, gold, tag='meaning'):
    descriptions = descriptions.split('|')
    # Keep a stable meaning key, but balance the displayed gold position for each K.
    k = len(descriptions)
    p = min(range(k), key=lambda i: (position_counts[(id(bank), k, i)], i))
    position_counts[(id(bank), k, p)] += 1
    original = list(enumerate(descriptions))
    correct = original.pop(gold)
    original.insert(p, correct)
    criteria = {f'option_{i}': d for i, (_, d) in enumerate(original)}
    add('choice', state, instructions, criteria, f'option_{p}', tag)

def n(state, instructions, gold, tag='entailment'):
    add('noul', state, instructions, {'false': 'いいえ', 'true': 'はい'}, gold, tag)

def s(state, instructions, descriptions, gold, tag='rubric'):
    add('score', state, instructions, descriptions.split('|'), gold, tag)

